DATASET_VERSION = "0.1.0"
IMAGE_DPI = 200
IGNORED_RELEASE_DIRS = {".tmp", "failed", "runs"}
DOC_ID = re.compile(r"^[a-z][a-z0-9_]*_\d{6}$")
SHA256 = re.compile(r"^[0-9a-f]{64}$")

DATASET_CARD = """# OCR Research Benchmark Dataset

Dataset version: `0.1.0`  
Bundle contract: `0.2.0`  
Taxonomy: `0.1.0`

## Contents

`documents/<doc_type>/<doc_id>/` contains one offline, labeled HTML page per
page, semantic content and pagination JSON, the generation spec and trace,
local assets, and a matching PNG image for OCR input. Images are rendered at
200 DPI; the DPI is also recorded in each `document.json`.

`index/documents.jsonl` and `index/pages.jsonl` describe the bundles.
`index/stats.json` summarizes document, page, and block counts.
`index/checksums.sha256` covers the released files other than itself. Rebuild
the index with `.venv/bin/factory index` and validate it with
`.venv/bin/factory verify`.

## How it was made

Documents are generated by Benchmark Factory from versioned prompts, taxonomy,
contract, templates, and seeded layout choices. The factory records the seed,
versions, prompt hash, model trace, and run coverage. Generated company names,
people, addresses, and financial figures are fictional. `runs/`, `failed/`,
and staging data are retained locally but excluded from release archives.

## Loading

Read `index/documents.jsonl` as UTF-8 JSON Lines. For each row, load the bundle
from `documents/{type}/{id}/`. Use `document.json` for page roles, dimensions,
and image DPI; `pages/page_NNN.html` carries labels, and
`images/page_NNN.png` is the corresponding OCR input.

## License

No dataset license has been assigned yet. This card does not grant permission
to redistribute the dataset. Select and record a license before publishing a
release archive.
"""


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def factory_version() -> str:
    data = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    return data["project"]["version"]


def prepare_dataset(root: Path) -> None:
    """Create missing top-level dataset metadata without overwriting it."""
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    if not (root / "README.md").exists():
        (root / "README.md").write_text(DATASET_CARD, encoding="utf-8")
    if not (root / "VERSION").exists():
        (root / "VERSION").write_text(DATASET_VERSION + "\n", encoding="utf-8")
    contract = root / "contract"
    contract.mkdir(exist_ok=True)
    contract_doc = contract / "CONTRACT.md"
    if not contract_doc.exists():
        source = (ROOT / "factory/contract/CONTRACT.md").read_text(encoding="utf-8")
        source = source.replace("../../configs/taxonomy.yaml", "taxonomy.yaml")
        contract_doc.write_text(source, encoding="utf-8")
    taxonomy = contract / "taxonomy.yaml"
    if not taxonomy.exists():
        taxonomy.write_bytes((ROOT / "configs/taxonomy.yaml").read_bytes())
    (root / ".tmp").mkdir(exist_ok=True)


def dataset_provenance(root: Path, prompts_sha256: str) -> dict[str, str]:
    """Return immutable source hashes for one generated document."""
    return {
        "factory_version": factory_version(),
        "contract_sha256": sha256_file(root / "contract/CONTRACT.md"),
        "taxonomy_sha256": sha256_file(root / "contract/taxonomy.yaml"),
        "prompts_sha256": prompts_sha256,
    }


def _json_line(value) -> bytes:
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode("utf-8")


def _load_bundle(bundle: Path):
    try:
        manifest = DocumentManifest.model_validate_json((bundle / "document.json").read_text(encoding="utf-8"))
        spec = BaseSpec.model_validate_json((bundle / "spec.json").read_text(encoding="utf-8"))
        trace = Trace.model_validate_json((bundle / "trace.json").read_text(encoding="utf-8"))
        return manifest, spec, trace
    except (OSError, ValueError) as exc:
        raise ValueError(f"Incomplete document bundle {bundle}: {exc}") from exc


def _document_bundle_paths(root: Path) -> list[Path]:
    documents = root / "documents"
    if not documents.exists():
        return []
    if not documents.is_dir():
        raise ValueError(f"documents is not a directory: {documents}")
    bundles = []
    for type_dir in sorted(documents.iterdir()):
        if not type_dir.is_dir() or not re.fullmatch(r"[a-z][a-z0-9_]*", type_dir.name):
            raise ValueError(f"Orphan entry under documents/: {type_dir}")
        children = sorted(type_dir.iterdir())
        if not children:
            raise ValueError(f"Empty document type directory: {type_dir}")
        for bundle in children:
            if not bundle.is_dir() or not DOC_ID.fullmatch(bundle.name):
                raise ValueError(f"Orphan or partial bundle path: {bundle}")
            if not bundle.name.startswith(type_dir.name + "_"):
                raise ValueError(f"Bundle ID does not match its type directory: {bundle}")
            bundles.append(bundle)
    return bundles


def _read_page(bundle: Path, manifest: DocumentManifest, entry):
    page_path = bundle / entry.file
    try:
        html = page_path.read_text(encoding="utf-8")
    except OSError as exc:
        raise ValueError(f"Missing page file {page_path}: {exc}") from exc
    page = parse_html(html)
    bodies = [node for node in page.walk() if node.tag == "body"]
    if len(bodies) != 1:
        raise ValueError(f"Expected one body in {page_path}")
    body = bodies[0]
    blocks = [node for node in body.walk() if node.attrs.get("data-gt-id")]
    counts = Counter(node.attrs.get("data-gt-cat", "unknown") for node in blocks)
    reading_orders = []
    for node in blocks:
        try:
            reading_orders.append(int(node.attrs["data-gt-ro"]))
        except (KeyError, ValueError):
            raise ValueError(f"Missing or invalid reading order in {page_path}")
    return {
        "page_id": entry.page_id,
        "doc_id": manifest.doc_id,
        "index": entry.index,
        "role": entry.role,
        "lang": body.attrs.get("data-page-lang", ""),
        "layout": body.attrs.get("data-page-layout", ""),
        "ro_level": max(reading_orders, default=0),
        "block_counts": dict(sorted(counts.items())),
    }


def index_payloads(root: Path) -> dict[str, bytes]:
    """Build all deterministic index data in memory from published bundles."""
    root = Path(root)
    document_rows, page_rows = [], []
    doc_layouts, block_counts = Counter(), Counter()
    doc_types, languages = Counter(), Counter()
    for bundle in _document_bundle_paths(root):
        manifest, spec, trace = _load_bundle(bundle)
        if manifest.doc_type != bundle.parent.name or manifest.doc_id != bundle.name or spec.doc_id != manifest.doc_id:
            raise ValueError(f"Bundle metadata does not match folder name: {bundle}")
        if trace.doc_id != manifest.doc_id:
            raise ValueError(f"Trace ID does not match folder name: {bundle}")
        pages = [_read_page(bundle, manifest, entry) for entry in manifest.pages]
        if len(pages) != manifest.page_count or not pages:
            raise ValueError(f"Page list is empty or incomplete: {bundle}")
        layouts = sorted({page["layout"] for page in pages if page["layout"]})
        layout = layouts[0] if len(layouts) == 1 else "mixed" if layouts else "unknown"
        provenance = manifest.provenance
        document_rows.append({
            "id": manifest.doc_id,
            "type": manifest.doc_type,
            "lang": pages[0]["lang"],
            "layout": layout,
            "pages": manifest.page_count,
            "seed": spec.seed,
            "versions": {
                "dataset": manifest.dataset_version,
                "factory": provenance.get("factory_version", trace.factory_version),
                "contract": manifest.contract_version,
                "taxonomy": manifest.taxonomy_version,
                "prompts_sha256": provenance.get("prompts_sha256", ""),
                "contract_sha256": provenance.get("contract_sha256", ""),
                "taxonomy_sha256": provenance.get("taxonomy_sha256", ""),
            },
            "status": trace.status,
        })
        page_rows.extend(pages)
        doc_types[manifest.doc_type] += 1
        languages[pages[0]["lang"]] += 1
        doc_layouts[layout] += 1
        for page in pages:
            block_counts.update(page["block_counts"])

    document_rows.sort(key=lambda row: (row["type"], row["id"]))
    page_rows.sort(key=lambda row: (row["doc_id"], row["index"]))
    stats = {
        "documents": len(document_rows),
        "pages": len(page_rows),
        "documents_by_type": dict(sorted(doc_types.items())),
        "documents_by_language": dict(sorted(languages.items())),
        "documents_by_layout": dict(sorted(doc_layouts.items())),
        "blocks_by_category": dict(sorted(block_counts.items())),
    }
    return {
        "index/documents.jsonl": b"".join(_json_line(row) for row in document_rows),
        "index/pages.jsonl": b"".join(_json_line(row) for row in page_rows),
        "index/stats.json": (json.dumps(stats, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8"),
    }


def _released_files(root: Path):
    for path in sorted(Path(root).rglob("*")):
        if not path.is_file():
            continue
        relative = path.relative_to(root)
        if relative.parts[0] in IGNORED_RELEASE_DIRS or relative.as_posix() == "index/checksums.sha256":
            continue
        yield path, relative.as_posix()


def checksum_bytes(root: Path) -> bytes:
    rows = [f"{sha256_file(path)}  {relative}\n" for path, relative in _released_files(root)]
    return "".join(rows).encode("utf-8")


def rebuild_index(root: Path) -> None:
    """Rebuild the generation indexes from accepted bundles."""
    root = Path(root)
    index_dir = root / "index"
    index_dir.mkdir(parents=True, exist_ok=True)
    rows = []
    for path in sorted((root / "documents").glob("*/*/document.json")):
        manifest = DocumentManifest.model_validate_json(path.read_text(encoding="utf-8"))
        spec = BaseSpec.model_validate_json((path.parent / "spec.json").read_text(encoding="utf-8"))
        rows.append(DocumentIndexEntry(
            doc_id=manifest.doc_id,
            doc_type=manifest.doc_type,
            lang=spec.lang,
            pages=manifest.page_count,
            path=path.parent.relative_to(root).as_posix(),
        ))
    (index_dir / "documents.jsonl").write_text(
        "".join(row.model_dump_json() + "\n" for row in rows), encoding="utf-8"
    )
    designs = index_dir / "designs.jsonl"
    if not designs.exists():
        designs.write_text("", encoding="utf-8")
    from factory.runner.languages import stats as language_stats
    report = LanguageStats.model_validate(language_stats(root))
    (index_dir / "languages.json").write_text(report.model_dump_json(indent=2) + "\n", encoding="utf-8")


async def verify_output(root: Path, browser, taxonomy) -> list[str]:
    """Verify generated bundles and the contracted output tree."""
    from factory.contract.models import (
        DesignLedgerEntry,
        DocSpec,
        DocumentIndexEntry,
        ProblemsRecord,
        RunRecord,
    )
    from factory.runner.layout import check_tree

    root = Path(root)
    errors = check_tree(root)
    for manifest_path in sorted((root / "documents").glob("*/*/document.json")):
        folder = manifest_path.parent
        try:
            manifest = DocumentManifest.model_validate_json(manifest_path.read_text(encoding="utf-8"))
            spec = DocSpec.model_validate_json((folder / "spec.json").read_text(encoding="utf-8"))
            Trace.model_validate_json((folder / "trace.json").read_text(encoding="utf-8"))
            SourceContent.model_validate_json((folder / "source_content.json").read_text(encoding="utf-8"))
            if spec.design in ("agent", "legacy"):
                DesignSpec.model_validate_json((folder / "design/design_spec.json").read_text(encoding="utf-8"))
            for page in manifest.pages:
                image_path = folder / "images" / f"page_{page.index:03}.png"
                with Image.open(image_path) as image:
                    expected = (round(page.width_mm / 25.4 * IMAGE_DPI), round(page.height_mm / 25.4 * IMAGE_DPI))
                    if image.format != "PNG" or any(abs(actual - wanted) > 1 for actual, wanted in zip(image.size, expected)):
                        errors.append(f"Image dimensions/format mismatch: {image_path}")
            issues = await lint_document(folder, browser, taxonomy)
            errors.extend(f"{folder.name}: {issue.rule_id} {issue.message}" for issue in issues)
        except (OSError, ValueError) as exc:
            errors.append(f"Invalid bundle {folder}: {exc}")
    for path in sorted((root / "failed").glob("*/*")):
        try:
            ProblemsRecord.model_validate_json((path / "problems.json").read_text(encoding="utf-8"))
            Trace.model_validate_json((path / "trace.json").read_text(encoding="utf-8"))
            DocSpec.model_validate_json((path / "spec.json").read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            errors.append(f"Invalid failed record {path}: {exc}")
    for path in sorted((root / "runs").glob("*/run.json")):
        try:
            run = RunRecord.model_validate_json(path.read_text(encoding="utf-8"))
            if run.run_id != path.parent.name:
                errors.append(f"Run ID mismatch: {path.parent}")
        except (OSError, ValueError) as exc:
            errors.append(f"Invalid run record {path}: {exc}")
    index = root / "index"
    for name, model, description in (
        ("documents.jsonl", DocumentIndexEntry, "document index row"),
        ("designs.jsonl", DesignLedgerEntry, "design ledger row"),
    ):
        path = index / name
        if not path.is_file():
            continue
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
            for line in lines:
                model.model_validate_json(line)
        except (OSError, ValueError) as exc:
            errors.append(f"Invalid {description}: {exc}")
    languages_path = index / "languages.json"
    if languages_path.is_file():
        try:
            LanguageStats.model_validate_json(languages_path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            errors.append(f"Invalid language stats: {exc}")
    return errors


def _verify_scaffold(root: Path, errors: list[str]) -> tuple[str | None, str | None, str | None]:
    version_path = root / "VERSION"
    contract_path = root / "contract/CONTRACT.md"
    taxonomy_path = root / "contract/taxonomy.yaml"
    for path in (root / "README.md", version_path, contract_path, taxonomy_path):
        if not path.is_file():
            errors.append(f"Missing dataset metadata: {path.relative_to(root)}")
    version = version_path.read_text(encoding="utf-8").strip() if version_path.is_file() else None
    contract_version = taxonomy_version = None
    if contract_path.is_file():
        match = re.search(r"^Version:\s+\*\*([^*]+)\*\*", contract_path.read_text(encoding="utf-8"), re.M)
        if match:
            contract_version = match.group(1)
        else:
            errors.append("contract/CONTRACT.md has no parseable version")
    if taxonomy_path.is_file():
        try:
            taxonomy_version = str(yaml.safe_load(taxonomy_path.read_text(encoding="utf-8"))["version"])
        except (KeyError, TypeError, yaml.YAMLError) as exc:
            errors.append(f"contract/taxonomy.yaml is invalid: {exc}")
    if contract_version and contract_version != CONTRACT_VERSION:
        errors.append(f"Contract version is {contract_version}; code expects {CONTRACT_VERSION}")
    return version, contract_version, taxonomy_version


def _verify_failed(root: Path, errors: list[str]) -> set[str]:
    failed_root = root / "failed"
    ids = set()
    if not failed_root.exists():
        return ids
    for type_dir in sorted(failed_root.iterdir()):
        if not type_dir.is_dir() or not re.fullmatch(r"[a-z][a-z0-9_]*", type_dir.name):
            errors.append(f"Orphan entry under failed/: {type_dir}")
            continue
        for folder in sorted(type_dir.iterdir()):
            if not folder.is_dir() or not DOC_ID.fullmatch(folder.name) or not folder.name.startswith(type_dir.name + "_"):
                errors.append(f"Orphan or partial failed folder: {folder}")
                continue
            try:
                spec = BaseSpec.model_validate_json((folder / "spec.json").read_text(encoding="utf-8"))
                trace = Trace.model_validate_json((folder / "trace.json").read_text(encoding="utf-8"))
                if spec.doc_id != folder.name or trace.doc_id != folder.name or trace.status != "failed":
                    errors.append(f"Failed bundle metadata mismatch: {folder}")
            except (OSError, ValueError) as exc:
                errors.append(f"Incomplete failed bundle {folder}: {exc}")
            ids.add(folder.name)
    return ids


def _verify_runs(root: Path, errors: list[str]) -> None:
    runs = root / "runs"
    if not runs.exists():
        return
    for folder in sorted(runs.iterdir()):
        if not folder.is_dir():
            errors.append(f"Orphan entry under runs/: {folder}")
            continue
        try:
            run = json.loads((folder / "run.json").read_text(encoding="utf-8"))
            coverage = json.loads((folder / "coverage.json").read_text(encoding="utf-8"))
            if run.get("run_id") != folder.name or coverage.get("run_id") != folder.name:
                errors.append(f"Run ID mismatch: {folder}")
            if not isinstance(coverage.get("documents"), list):
                errors.append(f"Malformed run coverage: {folder}")
        except (OSError, ValueError) as exc:
            errors.append(f"Incomplete run record {folder}: {exc}")


async def verify_dataset(root: Path, browser, taxonomy) -> list[str]:
    """Check bundle lint, metadata, indexes, images, checksums and partial paths."""
    root = Path(root)
    errors: list[str] = []
    version, contract_version, taxonomy_version = _verify_scaffold(root, errors)
    if taxonomy_version and taxonomy_version != taxonomy.version:
        errors.append(f"Taxonomy version is {taxonomy_version}; code expects {taxonomy.version}")
    known = {"README.md", "VERSION", "contract", "documents", "failed", "runs", "index", ".tmp"}
    for entry in root.iterdir() if root.exists() else ():
        if entry.name not in known:
            errors.append(f"Unexpected top-level dataset entry: {entry.name}")
    temp = root / ".tmp"
    if temp.exists() and any(temp.rglob("*")):
        errors.append("out/.tmp contains orphan or partial staging data")
    index_dir = root / "index"
    if index_dir.exists():
        expected_index_files = {"documents.jsonl", "pages.jsonl", "stats.json", "checksums.sha256"}
        actual_index_files = {path.name for path in index_dir.iterdir() if path.is_file()}
        if actual_index_files != expected_index_files:
            errors.append(f"Unexpected or missing index files: {sorted(actual_index_files ^ expected_index_files)}")
    failed_ids = _verify_failed(root, errors)
    bundles = []
    try:
        bundles = _document_bundle_paths(root)
    except ValueError as exc:
        errors.append(str(exc))
    document_ids = set()
    for bundle in bundles:
        manifest = None
        try:
            manifest, spec, trace = _load_bundle(bundle)
            document_ids.add(manifest.doc_id)
            if manifest.doc_id in failed_ids:
                errors.append(f"Document ID appears in both documents/ and failed/: {manifest.doc_id}")
            if manifest.dataset_version != version:
                errors.append(f"Dataset version mismatch in {bundle}: {manifest.dataset_version} != {version}")
            if manifest.contract_version != contract_version:
                errors.append(f"Contract version mismatch in {bundle}: {manifest.contract_version} != {contract_version}")
            if manifest.taxonomy_version != taxonomy_version:
                errors.append(f"Taxonomy version mismatch in {bundle}: {manifest.taxonomy_version} != {taxonomy_version}")
            provenance = manifest.provenance
            for field, expected in (("contract_sha256", root / "contract/CONTRACT.md"),
                                    ("taxonomy_sha256", root / "contract/taxonomy.yaml")):
                value = provenance.get(field, "")
                if not SHA256.fullmatch(value) or (expected.is_file() and value != sha256_file(expected)):
                    errors.append(f"Invalid {field} in {bundle}")
            if not SHA256.fullmatch(provenance.get("prompts_sha256", "")):
                errors.append(f"Invalid prompts_sha256 in {bundle}")
            if provenance.get("factory_version") != trace.factory_version:
                errors.append(f"Factory version mismatch in {bundle}")
            prompt_events = [event.detail.get("prompts_sha256") for event in trace.events
                             if event.stage == "config" and event.detail.get("prompts_sha256")]
            if provenance.get("prompts_sha256") not in prompt_events:
                errors.append(f"Prompt hash is missing from trace in {bundle}")
            if manifest.image_dpi != IMAGE_DPI:
                errors.append(f"Unsupported image DPI in {bundle}: {manifest.image_dpi}")
            image_dir = bundle / "images"
            expected_images = {f"page_{page.index:03}.png" for page in manifest.pages}
            actual_images = {path.name for path in image_dir.glob("*.png")} if image_dir.is_dir() else set()
            if actual_images != expected_images:
                errors.append(f"Page images differ from document manifest in {bundle}")
            else:
                for page in manifest.pages:
                    image_path = image_dir / f"page_{page.index:03}.png"
                    try:
                        with Image.open(image_path) as image:
                            expected_size = (round(page.width_mm / 25.4 * IMAGE_DPI),
                                             round(page.height_mm / 25.4 * IMAGE_DPI))
                            if image.format != "PNG" or any(abs(actual - target) > 1 for actual, target in zip(image.size, expected_size)):
                                errors.append(f"Image dimensions/format mismatch: {image_path}")
                    except OSError as exc:
                        errors.append(f"Unreadable page image {image_path}: {exc}")
            issues = await lint_document(bundle, browser, taxonomy)
            if issues:
                errors.append(f"Lint found {len(issues)} issue(s) in {bundle}: " + "; ".join(f"{i.rule_id} {i.level}" for i in issues))
        except (OSError, ValueError) as exc:
            errors.append(f"Invalid document bundle {bundle}: {exc}")
    if document_ids & failed_ids:
        errors.append("Document IDs are not unique across documents/ and failed/")
    _verify_runs(root, errors)
    try:
        expected_indexes = index_payloads(root)
        for relative, payload in expected_indexes.items():
            path = root / relative
            if not path.is_file() or path.read_bytes() != payload:
                errors.append(f"Index is stale or missing: {relative}")
        checksums_path = root / "index/checksums.sha256"
        if not checksums_path.is_file() or checksums_path.read_bytes() != checksum_bytes(root):
            errors.append("index/checksums.sha256 is stale or incorrect")
    except (OSError, ValueError) as exc:
        errors.append(f"Unable to rebuild expected index: {exc}")
    return errors

