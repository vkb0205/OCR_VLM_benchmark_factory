class TemplateError(ValueError):
    def __init__(self, problems):
        self.problems = list(problems)
        super().__init__('\n'.join(self.problems))


def serialize(node):
    if isinstance(node, str):
        return escape(node)
    attrs = ''.join(f' {k}="{escape(str(v), quote=True)}"' for k,v in node.attrs.items())
    if node.tag == 'document': return ''.join(serialize(c) for c in node.children)
    # Style and script are raw-text elements.
    inner = ''.join(node.children) if node.tag in {'style','script'} else ''.join(serialize(c) for c in node.children)
    return f'<{node.tag}{attrs}>' + ('' if node.tag in VOID else inner + f'</{node.tag}>')


def ancestors(node):
    while node.parent:
        node = node.parent
        yield node


def validate_template(source, config, taxonomy):
    root = parse_html(source)
    problems = []
    fields = {f.id:f for f in config.fields}
    sections = [n for n in root.walk() if n.tag=='section' and 'page' in n.attrs.get('class','').split()]
    if not sections: problems.append('No section.page elements')
    counts = dict.fromkeys(fields, 0)
    for n in root.walk():
        if 'data-chain' in n.attrs:
            try:
                if 'data-region' not in n.attrs or int(n.attrs['data-chain']) < 1:
                    raise ValueError()
            except ValueError:
                problems.append('data-chain must be a positive integer on a data-region')
        elif 'data-region' in n.attrs:
            problems.append('data-region requires data-chain')
        if 'data-float-policy' in n.attrs and n.attrs['data-float-policy'] not in {'here', 'top_column', 'top_page', 'next_page'}:
            problems.append('Unknown float placement policy')
        if 'data-float-span' in n.attrs:
            try:
                if not 1 <= int(n.attrs['data-float-span']) <= 5:
                    raise ValueError()
            except ValueError:
                problems.append('data-float-span must be an integer from 1 to 5')
        slot = n.attrs.get('data-slot')
        label = n.attrs.get('data-label')
        if n.tag in {'script','iframe','object','embed','base'}:
            problems.append(f'<{n.tag}> is not allowed')
        if any(k.startswith('on') or k.startswith('data-gt-') and k != 'data-gt-ignore' for k in n.attrs):
            problems.append('Template labels and event handlers must be generated by code')
        if (slot is not None or label) and not any(x in sections for x in ancestors(n)):
            problems.append('Slots and labels must be inside a page')
        if slot is not None:
            if slot not in fields: problems.append(f'Unknown slot {slot}')
            else:
                counts[slot] += 1
                f = fields[slot]
                if f.kind in {'table','statement'} and (n.tag != 'table' or not taxonomy.valid_attribute('block','frame_type',n.attrs.get('data-frame',''))):
                    problems.append(f'{slot}: table requires data-frame with a valid frame type')
            if not any(x in sections for x in ancestors(n)): problems.append(f'{slot}: slot must be inside a page')
        if label and label not in taxonomy.text: problems.append(f'Unknown text data-label {label}')
        if label and slot: problems.append('An element cannot have both data-slot and data-label')
        if slot or label:
            if any('data-slot' in a.attrs or 'data-label' in a.attrs for a in ancestors(n)):
                problems.append('Nested slots/labels are not allowed')
        if 'data-order' in n.attrs:
            try: int(n.attrs['data-order'])
            except ValueError: problems.append('data-order must be an integer')
        if 'data-item' in n.attrs and not re.fullmatch(r'[a-z][a-z0-9]*',n.attrs['data-item']):
            problems.append('data-item must be an HTML tag')
        raw_text = ''.join(c for node in n.walk() for c in node.children if isinstance(c, str))
        if 'data-gt-ignore' in n.attrs and normalize(raw_text):
            problems.append('data-gt-ignore is only for decorations without text')
        if n.tag not in {'style','title'}:
            for child in n.children:
                if isinstance(child,str) and normalize(child) and not any('data-slot' in a.attrs or 'data-label' in a.attrs for a in [n,*ancestors(n)]):
                    problems.append('Visible text outside slots and data-label')
                    break
        for k,v in n.attrs.items():
            if k in {'src','href','xlink:href','srcset','action'} and (re.search(r'^(?:[a-z]+:|//|/)|\.\.',v,re.I) or not v.startswith('assets/')):
                problems.append(f'External or unsafe URL: {v}')
    for sid,count in counts.items():
        if count != 1: problems.append(f'{sid}: field must be placed exactly once (found {count})')
    for section in sections:
        if not section.attrs.get('data-page-role'): problems.append('section.page requires data-page-role')
        if section.attrs.get('data-size','a4') not in SIZES:
            problems.append('data-size must be one of ' + ', '.join(SIZES))
        if not taxonomy.valid_attribute('page','layout',section.attrs.get('data-layout','single_column')): problems.append('Invalid data-layout')
        level = section.attrs.get('data-ro-level')
        if level is not None and level not in {'L0', 'L1', 'L2', 'L3', 'L4'}:
            problems.append('data-ro-level must be L0 through L4')
        regions = [n for n in section.walk() if 'data-region' in n.attrs]
        chains = [int(n.attrs['data-chain']) for n in regions if n.attrs.get('data-chain', '').isdigit()]
        if len(chains) != len(set(chains)):
            problems.append('data-chain values must be unique within a page')
        if chains != sorted(chains):
            problems.append('data-region elements must follow ascending data-chain order')
    css = '\n'.join(''.join(n.children) for n in root.walk() if n.tag=='style') + '\n' + '\n'.join(n.attrs.get('style','') for n in root.walk())
    if re.search(r'text-transform\s*:\s*(?!none\b)',css,re.I): problems.append('text-transform is not allowed')
    urls = [url.strip().strip("'\"") for url in re.findall(r'url\(\s*([^)]*)\)', css, re.I)]
    if re.search(r'@import', css, re.I) or any(not url.startswith('assets/') or '..' in url for url in urls):
        problems.append('External CSS URLs and imports are not allowed')
    for value in re.findall(r'(?:^|[;{])\s*content\s*:\s*([^;}]+)',css,re.I):
        if value.strip().lower() not in {"''",'""','none','normal'}: problems.append('CSS generated text must use data-label')
    if problems: raise TemplateError(problems)
    return root, sections


def replace_inner(node, html):
    node.children = parse_html(html).children
    for c in node.children:
        if isinstance(c,Element): c.parent = node


def font_css():
    # Pages live in pages/ beside assets/, where fill() always copies this font.
    return "@font-face {font-family:'Factory Serif';src:url('../assets/fonts/NotoSerif-Regular.ttf') format('truetype');font-weight:400;font-style:normal;}"


